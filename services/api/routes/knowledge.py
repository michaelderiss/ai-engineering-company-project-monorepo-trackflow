"""
Milestone 7 — RAG Knowledge Base
==================================
Phase 3 — FastAPI query endpoint.

POST /knowledge/query
  Request:  { "question": "..." }
  Response: { "answer": "..." }

The endpoint imports and calls ``query()`` from ``data/pipelines/rag`` —
no duplicated retrieval or generation logic lives here.
"""

from __future__ import annotations

import logging

from fastapi import APIRouter
from pydantic import BaseModel, Field

from data.pipelines.rag import query as rag_query

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/knowledge", tags=["knowledge"])


class QueryRequest(BaseModel):
    question: str = Field(..., min_length=1, description="Natural-language question about TrackFlow policies.")


class QueryResponse(BaseModel):
    answer: str = Field(..., description="Model-generated answer based on retrieved knowledge-base chunks.")


@router.post("/query", response_model=QueryResponse)
def knowledge_query(payload: QueryRequest) -> QueryResponse:
    """Answer a natural-language question using the TrackFlow knowledge base.

    The answer is always generated by the model from retrieved context —
    never raw vector-database results.
    """
    answer = rag_query(payload.question)
    logger.info("Knowledge query answered (length=%d chars)", len(answer))
    return QueryResponse(answer=answer)
